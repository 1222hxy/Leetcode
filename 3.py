class Solution:
    def lengthOfLongestSubstring(self, s: str) -> int:
        left = 0
        right = 0
        max_len = 0
        my_set = set()

        while right < len(s):
            if s[right] in my_set:
                my_set.remove(s[left])
                left += 1
            else:
                my_set.add(s[right])
                max_len = max(max_len, len(my_set))
                right += 1

        return max_len

